/* ------------------------------------------------------------------ */
/* Decision.                                                           */
/* ------------------------------------------------------------------ */

bool shouldElevate(const cli::Args& args)
{
    /* Already root: nothing to ask for. */
    if (::geteuid() == 0) return false;

    /* Explicit bypass (automated tests, containers, debugging):
     * the responsibility falls back on the user. */
    const char* noElevate = ::getenv("PRISM_INSTALLER_NO_ELEVATE");
    if (noElevate && *noElevate) return false;

    /* Paths that never touch a real disk. */
    if (args.help || args.version || !args.errors.empty()) return false;
    if (args.guiSelfTest) return false;

    /* --check mode (read-only audit): only a block device requires
     * root (read rights); an image is audited without any
     * privileges, and the absence of a target is a simple usage
     * error. */
    if (args.check) {
        const std::string& t = args.options.target;
        return !t.empty()
               && (t.rfind("/dev/", 0) == 0 || isBlockDevice(t));
    }

    /* Explicit target: only block devices require root.
     * An image file (QEMU tests) installs without any privileges -
     * elevating it would only create a file owned by root. */
    const std::string& t = args.options.target;
    if (!t.empty())
        return t.rfind("/dev/", 0) == 0 || isBlockDevice(t);

    /* Without an explicit target:
     *  - graphical mode: the Disk page targets a real disk, we
     *    elevate right away, exactly like Calamares (launched via pkexec);
     *  - real interactive text assistant (terminal): same;
     *  - --yes without --disk: immediate error expected, no point elevating;
     *  - non-interactive input (stdin redirected, scripts, CI): no
     *    elevation, so automations are not broken. */
    if (guiLaunch(args)) return true;
    return !args.yes && ::isatty(STDIN_FILENO) == 1;
}

/* ------------------------------------------------------------------ */
/* Elevated relaunch.                                                     */
/* ------------------------------------------------------------------ */

int relaunchElevated(int argc, char** argv, const cli::Args& args)
{
    const bool graphical = guiLaunch(args);

    std::string self = selfPath();
    if (self.empty()) {
        std::fprintf(stderr,
                     "prism-installer: unable to locate the current "
                     "binary (/proc/self/exe) - elevation abandoned.\n");
        return ELEVATE_FAILED;
    }

    /* Original command line, without argv[0], passed back as-is:
     * spaces, accents and parentheses included (argv is not
     * interpreted by a shell). */
    std::vector<std::string> rest;
    rest.reserve(size_t(argc > 1 ? argc - 1 : 0));
    for (int i = 1; i < argc; ++i) rest.emplace_back(argv[i]);

    /* ---- Text mode: sudo in the terminal --------------------------- */

    if (!graphical) {
        std::string sudo = prism::which("sudo");
        if (sudo.empty()) {
            std::fprintf(stderr,
                         "prism-installer: sudo not found and administrator "
                         "privileges are required to write a disk.\nInstall "
                         "sudo, or run as root (e.g. \"su -c\").\n");
            return ELEVATE_FAILED;
        }
        std::fprintf(stderr,
                     "prism-installer: administrator privileges required - "
                     "requesting privileges via sudo...\n");
        std::vector<std::string> words{ sudo, "--", self };
        words.insert(words.end(), rest.begin(), rest.end());
        int err = execWords(words);
        std::fprintf(stderr,
                     "prism-installer: failed to launch sudo: %s\n",
                     std::strerror(err));
        return ELEVATE_FAILED;
    }

    /* ---- Graphical mode: pkexec, then sudo -A, then sudo ----------- */

    /* Common tail: env VAR=value... <binary> <args...>.  Going through
     * /usr/bin/env is the standard way to set variables for the
     * program re-executed by pkexec/sudo (both of which strip the
     * inherited environment). */
    std::vector<std::string> tail;
    std::string envBin = prism::which("env");
    if (!envBin.empty()) {
        tail.push_back(envBin);
        for (const auto& a : displayEnvAssignments()) tail.push_back(a);
    }
    tail.push_back(self);
    tail.insert(tail.end(), rest.begin(), rest.end());

    /* 1) pkexec: desktop authentication dialog (polkit).
     *    This is the mechanism used by Calamares.  A user refusal
     *    is handled by pkexec itself (code 126); the process having
     *    been replaced, nothing comes back here. */
    std::string pkexec = prism::which("pkexec");
    if (!pkexec.empty()) {
        std::vector<std::string> words{ pkexec };
        words.insert(words.end(), tail.begin(), tail.end());
        int err = execWords(words);
        std::fprintf(stderr,
                     "prism-installer: pkexec could not be launched (%s), "
                     "trying sudo...\n", std::strerror(err));
    }

    std::string sudo = prism::which("sudo");
    if (sudo.empty()) {
        std::fprintf(stderr,
                     "prism-installer: neither pkexec nor sudo is available "
                     "- unable to obtain administrator privileges "
                     "automatically.\nInstall polkit (pkexec) or sudo, or "
                     "launch the installer from a terminal.\n");
        return ELEVATE_FAILED;
    }

    /* 2) sudo -A: graphical input dialog (zenity or kdialog) when
     *    the desktop offers no polkit. */
    std::string askpass = makeAskpassScript();
    if (!askpass.empty()) {
        ::setenv("SUDO_ASKPASS", askpass.c_str(), 1);
        std::vector<std::string> words{ sudo, "-A", "--" };
        words.insert(words.end(), tail.begin(), tail.end());
        int err = execWords(words);
        std::fprintf(stderr,
                     "prism-installer: sudo -A could not be launched (%s), "
                     "trying sudo in the terminal...\n",
                     std::strerror(err));
    }

    /* 3) plain sudo: password prompt in the terminal the installer
     *    was launched from. */
    std::vector<std::string> words{ sudo, "--" };
    words.insert(words.end(), tail.begin(), tail.end());
    int err = execWords(words);
    std::fprintf(stderr,
                 "prism-installer: failed to launch sudo: %s\n",
                 std::strerror(err));
    return ELEVATE_FAILED;
}

/* ------------------------------------------------------------------ */
/* Sanitizing the environment of the elevated process.                 */
/* ------------------------------------------------------------------ */

void sanitizeEnvAsRoot()
{
    if (::geteuid() != 0) return;

    /* Wayland: the server socket ($XDG_RUNTIME_DIR/wayland-0) lives
     * there - do not touch it, even at the cost of keeping the Qt
     * warnings (the Wayland connection of a root process is in any
     * case often refused; it is the X11 fallback via DISPLAY that is
     * used). */
    const char* way = ::getenv("WAYLAND_DISPLAY");
    if (way && *way) return;

    const char* xdgr = ::getenv("XDG_RUNTIME_DIR");
    if (!xdgr || !*xdgr) return;

    struct ::stat st{};
    if (::stat(xdgr, &st) == 0 && st.st_uid == 0)
        return;                 /* already root's directory */

    /* Private 0700 directory owned by root (mkdtemp creates 0700):
     * Qt stores its runtime files there without emitting the six
     * "runtime directory '/run/user/1000' is not
     * owned by UID 0" warnings observed after the elevation.  Harmless
     * residue in /tmp (tmpfs, purged at reboot): we are replaced by
     * exec right after the elevation and cannot delete it. */
    char tmpl[] = "/tmp/prism-installer-runtime-XXXXXX";
    if (::mkdtemp(tmpl))
        ::setenv("XDG_RUNTIME_DIR", tmpl, 1);
}

