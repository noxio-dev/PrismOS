/* True if graphical mode will be used (exact mirror of the routing in
 * main.cpp: --cli/--yes force text mode, otherwise a display server is
 * required - or an explicit QPA platform, e.g. offscreen in CI).
 * Since elevation happens BEFORE that routing, it must apply the
 * same decision. */
bool guiLaunch(const cli::Args& a)
{
    if (a.cli || a.yes || a.check) return false;
    const char* x11 = ::getenv("DISPLAY");
    const char* way = ::getenv("WAYLAND_DISPLAY");
    const char* qpa = ::getenv("QT_QPA_PLATFORM");
    return (x11 && *x11) || (way && *way) || (qpa && *qpa);
}

/* Absolute path of the current binary (/proc/self/exe stays correct
 * even if argv[0] is a relative or modified path - and will remain so
 * after the elevation, unlike argv[0]). */
std::string selfPath()
{
    char buf[4096];
    ssize_t n = ::readlink("/proc/self/exe", buf, sizeof(buf) - 1);
    if (n <= 0) return {};
    buf[n] = '\0';
    return buf;
}

/* execv() only returns on failure: return errno then, so the next
 * method can be tried.  The strings are duplicated because the array
 * must remain valid until the exec (and beyond). */
int execWords(const std::vector<std::string>& words)
{
    if (words.empty()) return EINVAL;
    std::vector<char*> v;
    v.reserve(words.size() + 1);
    for (const auto& w : words) v.push_back(::strdup(w.c_str()));
    v.push_back(nullptr);
    ::execv(words[0].c_str(), v.data());
    return errno;
}

/* Variables to pass to the elevated process so it can show its
 * window: without them, the root process re-executed by pkexec/sudo
 * would live in a stripped environment, with no DISPLAY or X cookie. */
std::vector<std::string> displayEnvAssignments()
{
    static const char* const vars[] = {
        "DISPLAY", "XAUTHORITY",
        "WAYLAND_DISPLAY", "XDG_RUNTIME_DIR", "XDG_SESSION_TYPE",
        "XDG_CURRENT_DESKTOP", "XDG_SESSION_DESKTOP",
        "QT_QPA_PLATFORM", "QT_QPA_PLATFORMTHEME", "QT_STYLE_OVERRIDE",
        "QT_SCALE_FACTOR", "QT_SCREEN_SCALE_FACTORS",
        "QT_AUTO_SCREEN_SCALE_FACTOR", "QT_ENABLE_HIGHDPI_SCALING",
        "QT_WAYLAND_DISABLE_WINDOWDECORATION",
    };
    std::vector<std::string> out;
    for (const char* v : vars) {
        const char* val = ::getenv(v);
        if (val && *val) out.push_back(std::string(v) + "=" + val);
    }
    return out;
}

/* Writes a small "askpass" script (zenity/kdialog dialog box) for
 * "sudo -A": last graphical resort when polkit is missing.
 * Returns "" if no input tool is available.  The file lives in /tmp
 * (cleaned at reboot): we are replaced by the exec right after and
 * cannot delete it ourselves. */
std::string makeAskpassScript()
{
    if (prism::which("zenity").empty() && prism::which("kdialog").empty())
        return {};

    char tmpl[] = "/tmp/prism-askpass-XXXXXX";
    int fd = ::mkstemp(tmpl);
    if (fd < 0) return {};
    std::FILE* f = ::fdopen(fd, "w");
    if (!f) {
        ::close(fd);
        ::unlink(tmpl);
        return {};
    }
    std::fputs("#!/bin/sh\n", f);
    std::fputs("# Generated by prism-installer: graphical request for the\n", f);
    std::fputs("# administrator password (sudo -A) when pkexec is missing.\n", f);
    std::fputs("if command -v zenity >/dev/null 2>&1; then\n", f);
    std::fputs("  exec zenity --password"
               " --title='prism-installer: administrator privileges'\n", f);
    std::fputs("fi\n", f);
    std::fputs("exec kdialog --password"
               " 'prism-installer: administrator password'\n", f);
    std::fclose(f);
    ::chmod(tmpl, 0700);
    return tmpl;
}

