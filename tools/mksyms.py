"""
Regenerate the kernel symbol table source (sys/kern/src/lib/kallsyms_data.rs)
from a linked kernel ELF:

    tools/mksyms.py <kernel-elf> <output-rs>

Only defined text symbols (T/t/W/w in `nm -n`) are kept, address-sorted, and
capped so that the generated table fits inside the fixed-size `.kallsyms`
section reserved by linker.ld (entries + names < budget).  The output is
compared against the existing file and rewritten only when it differs; the
exit code is 0 when the file was up to date and 1 when it changed (used by
the Makefile to trigger a second, converging build pass).
"""

import os
import subprocess
import sys

# Budgets matching linker.ld (.kallsyms is 128 KiB; leave slack).
MAX_ENTRIES = 6000          # 6000 * 12 = 70.3 KiB of entries
MAX_NAMES = 48000           # name bytes
MAX_NAME_LEN = 56


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    elf, out = sys.argv[1], sys.argv[2]

    try:
        nm = subprocess.run(["nm", "-n", "--defined-only", elf],
                            capture_output=True, text=True, check=True)
    except (OSError, subprocess.CalledProcessError) as e:
        sys.stderr.write("mksyms: nm failed: %s\n" % e)
        # Leave any existing table alone; do not fail the build.
        sys.exit(0)

    syms = []
    for line in nm.stdout.splitlines():
        parts = line.split(None, 2)
        if len(parts) != 3:
            continue
        addr_str, typ, name = parts
        if typ not in ("T", "t", "W", "w"):
            continue
        try:
            addr = int(addr_str, 16)
        except ValueError:
            continue
        if name.startswith(".") or "$" in name:
            continue
        syms.append((addr, name))

    # Deduplicate names (many functions can share one name after LTO).
    names = []
    name_off = {}
    entries = []
    for addr, name in syms:
        if len(entries) >= MAX_ENTRIES:
            break
        name = name[:MAX_NAME_LEN]
        off = name_off.get(name)
        if off is None:
            off = sum(len(n) + 1 for n in names)
            if off + len(name) + 1 > MAX_NAMES:
                break
            names.append(name)
            name_off[name] = off
        entries.append((addr, off))
    entries.sort()

    lines = []
    lines.append("// Generated by tools/mksyms.py -- DO NOT EDIT.")
    lines.append("pub const COUNT: usize = %d;" % len(entries))
    lines.append("pub const ENTRIES: [super::Sym; %d] = [" % len(entries))
    for addr, off in entries:
        lines.append("    (0x%016x, 0x%x)," % (addr, off))
    lines.append("];")
    blob = b"".join(n.encode() + b"\0" for n in names)
    lines.append("pub const NAMES: &[u8] = b\"%s\";" % "".join(
        "\\x%02x" % b for b in blob))
    text = "\n".join(lines) + "\n"

    old = ""
    if os.path.exists(out):
        with open(out) as f:
            old = f.read()
    if old == text:
        sys.exit(0)
    with open(out, "w") as f:
        f.write(text)
    sys.exit(1)  # changed: caller rebuilds


if __name__ == "__main__":
    main()
